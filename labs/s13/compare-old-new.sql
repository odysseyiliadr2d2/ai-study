-- 구·신 프로시저 결과 동일성 검증 (개발 DB, 읽기 전용 비교)
-- 1) 같은 기준일로 두 버전을 각각 실행해 결과를 별도 테이블에 적재해 둡니다.
--    OLD: DM_CUST_SUMMARY_OLD  (기존 커서 루프 버전)
--    NEW: DM_CUST_SUMMARY_NEW  (에이전트가 만든 집합 SQL 버전)

-- 2) 건수 · 합계 비교
SELECT 'OLD' AS VER, COUNT(*) AS CNT, SUM(BAL_AMT) AS SUM_BAL, SUM(TRX_CNT) AS SUM_TRX
  FROM DM_CUST_SUMMARY_OLD WHERE BASE_DT = :base_dt
UNION ALL
SELECT 'NEW', COUNT(*), SUM(BAL_AMT), SUM(TRX_CNT)
  FROM DM_CUST_SUMMARY_NEW WHERE BASE_DT = :base_dt;

-- 3) 행 단위 차이 — 두 쿼리 모두 0건이어야 '동일'로 판정합니다
SELECT 'ONLY_OLD' AS SIDE, o.* FROM (
  SELECT BASE_DT, CUST_GRP_CD, BRANCH_CD, BAL_AMT, TRX_CNT FROM DM_CUST_SUMMARY_OLD WHERE BASE_DT = :base_dt
  MINUS
  SELECT BASE_DT, CUST_GRP_CD, BRANCH_CD, BAL_AMT, TRX_CNT FROM DM_CUST_SUMMARY_NEW WHERE BASE_DT = :base_dt
) o
UNION ALL
SELECT 'ONLY_NEW', n.* FROM (
  SELECT BASE_DT, CUST_GRP_CD, BRANCH_CD, BAL_AMT, TRX_CNT FROM DM_CUST_SUMMARY_NEW WHERE BASE_DT = :base_dt
  MINUS
  SELECT BASE_DT, CUST_GRP_CD, BRANCH_CD, BAL_AMT, TRX_CNT FROM DM_CUST_SUMMARY_OLD WHERE BASE_DT = :base_dt
) n
FETCH FIRST 100 ROWS ONLY;

