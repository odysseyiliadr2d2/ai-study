"""app/db.py — Oracle 연결 · ORM 모델 · 저장소 함수 (세션 14의 store.py 를 대신합니다).

DATABASE_URL 예: oracle+oracledb://ticketdesk@localhost:1521/?service_name=FREEPDB1 (비밀번호는 DB_PASSWORD)
테스트는 sqlite+pysqlite:///:memory: 로 같은 코드를 돌립니다. 테이블은 DBA 가 DDL 로 만듭니다 (create_all 은 테스트만).
"""
import os
from datetime import date, datetime, timezone

from sqlalchemy import TIMESTAMP, Date, Identity, String, Text, create_engine, make_url, select
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, sessionmaker
from sqlalchemy.pool import StaticPool

from app.schemas import CreateRequest, Status

url = make_url(os.getenv("DATABASE_URL", "oracle+oracledb://ticketdesk@localhost:1521/?service_name=FREEPDB1"))
if os.getenv("DB_PASSWORD"):
    url = url.set(password=os.environ["DB_PASSWORD"])

if url.get_backend_name() == "sqlite":                      # 테스트용 메모리 DB
    engine = create_engine(url, connect_args={"check_same_thread": False}, poolclass=StaticPool)
else:
    engine = create_engine(url, pool_size=5, max_overflow=5, pool_pre_ping=True)

SessionLocal = sessionmaker(engine, expire_on_commit=False)


class Base(DeclarativeBase):
    pass


class WorkRequest(Base):
    """WORK_REQUEST 테이블. 소문자 이름은 Oracle 에서 따옴표 없는 대문자 이름(WORK_REQUEST)으로 나갑니다."""

    __tablename__ = "work_request"

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)         # NUMBER GENERATED BY DEFAULT AS IDENTITY
    title: Mapped[str] = mapped_column(String(100))
    body: Mapped[str] = mapped_column(Text)                               # CLOB
    due_date: Mapped[date | None] = mapped_column(Date)
    status: Mapped[str] = mapped_column(String(20), default="RECEIVED")
    category: Mapped[str | None] = mapped_column(String(20))
    priority: Mapped[str | None] = mapped_column(String(10))
    summary: Mapped[str | None] = mapped_column(String(1000))
    requester_id: Mapped[str] = mapped_column(String(50))
    created_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True),            # TIMESTAMP WITH TIME ZONE
                                                 default=lambda: datetime.now(timezone.utc))


def _visible(stmt, user):
    """담당자는 전체, 일반 사용자는 본인 것만 (Supabase 트랙의 RLS 를 서비스 계층에서)"""
    return stmt if user.is_handler else stmt.where(WorkRequest.requester_id == user.name)


def list_requests(user, status: Status | None = None) -> list[WorkRequest]:
    stmt = _visible(select(WorkRequest), user)
    if status:
        stmt = stmt.where(WorkRequest.status == status)
    stmt = stmt.order_by(WorkRequest.created_at.desc()).limit(100)        # Oracle: FETCH FIRST 100 ROWS ONLY
    with SessionLocal() as s:
        return list(s.scalars(stmt))


def get_request(user, request_id: int) -> WorkRequest | None:
    with SessionLocal() as s:
        return s.scalars(_visible(select(WorkRequest).where(WorkRequest.id == request_id), user)).first()


def create_request(data: CreateRequest, requester_id: str, analysis) -> WorkRequest:
    item = WorkRequest(title=data.title, body=data.body, due_date=data.due_date, requester_id=requester_id,
                       summary=analysis.summary if analysis else None,
                       category=analysis.category if analysis else None,
                       priority=analysis.priority if analysis else None)
    with SessionLocal.begin() as s:          # 짧은 트랜잭션: INSERT 하나 (LLM 호출은 이 밖에서 끝남)
        s.add(item)
    return item


def update_status(user, request_id: int, status: Status) -> WorkRequest | None:
    with SessionLocal.begin() as s:
        item = s.scalars(_visible(select(WorkRequest).where(WorkRequest.id == request_id), user)).first()
        if item is None:
            return None                        # 남의 요청은 '없음' — 존재 여부도 알려 주지 않습니다
        item.status = status                   # 변경 감지로 UPDATE
    return item
