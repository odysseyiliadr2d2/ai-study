-- 운영에서는 DBA 검토 후 반영합니다. 애플리케이션은 이 테이블을 만들지 않습니다(ddl-auto: none).

CREATE TABLE WORK_REQUEST (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TITLE         VARCHAR2(100 CHAR)           NOT NULL,
  BODY          CLOB                         NOT NULL,
  DUE_DATE      DATE,
  STATUS        VARCHAR2(20)  DEFAULT 'RECEIVED' NOT NULL,
  CATEGORY      VARCHAR2(20),
  PRIORITY      VARCHAR2(10),
  SUMMARY       VARCHAR2(1000 CHAR),
  REQUESTER_ID  VARCHAR2(50)                 NOT NULL,
  CREATED_AT    TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_WORK_REQUEST PRIMARY KEY (ID),
  CONSTRAINT CK_WORK_REQUEST_STATUS   CHECK (STATUS IN ('RECEIVED', 'IN_PROGRESS', 'DONE')),
  CONSTRAINT CK_WORK_REQUEST_CATEGORY CHECK (CATEGORY IN ('DATA_EXTRACT', 'BATCH_ISSUE', 'ACCESS', 'REPORT', 'ETC')),
  CONSTRAINT CK_WORK_REQUEST_PRIORITY CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH'))
);

-- 본인 요청 목록(최신순) 조회용
CREATE INDEX IX_WORK_REQUEST_01 ON WORK_REQUEST (REQUESTER_ID, CREATED_AT);
-- 담당자 상태별 목록 조회용
CREATE INDEX IX_WORK_REQUEST_02 ON WORK_REQUEST (STATUS, CREATED_AT);

COMMENT ON TABLE  WORK_REQUEST              IS '업무 요청';
COMMENT ON COLUMN WORK_REQUEST.BODY         IS '요청 본문 (한글 4000자 = 최대 약 12KB 라 CLOB)';
COMMENT ON COLUMN WORK_REQUEST.SUMMARY      IS 'AI 요약 (분석 실패 시 NULL)';
COMMENT ON COLUMN WORK_REQUEST.REQUESTER_ID IS '요청자 로그인 ID';

